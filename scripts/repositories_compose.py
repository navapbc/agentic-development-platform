"""Write the compose override that names the local tenants and mounts their repositories.

The tenants are the folders of config/local/tenants/ with their settings files, and the
repositories each tenant works on come from config/local/tenants/<tenant>/repositories.yaml, so
the committed compose files name none of them. This renders compose.repositories.yaml, which
gives the workflow worker and the repository intelligence services TENANTS, the list of every
tenant. It mounts read-only into the repository intelligence services each tenant's bundle
directory and every repository that names a path, at /tenants/<tenant>/repositories/<name>. The
in-cluster workers receive their copies through inv repos-sync.

A single-file bind mount keeps the inode it was created with, so an editor that saves
repositories.yaml by replacing the file is not seen inside the container. Each service carries
the label REGISTRY_LABEL, a digest of the registry files it mounts, so docker compose up -d
recreates the services once inv repos-compose runs after an edit.
"""

from __future__ import annotations

import argparse
import hashlib
import re
from collections.abc import Iterable, Sequence
from pathlib import Path, PurePosixPath
from typing import TYPE_CHECKING, Any

import yaml
from services.integration.credentials import env_config_dir

from scripts.config import Settings, get_settings

if TYPE_CHECKING:
    from services.integration.repositories import RepositoryRegistry

REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT = REPO_ROOT / "compose.repositories.yaml"
CONTAINER_ROOT = PurePosixPath("/app")
READERS = ("repo-intelligence", "repo-index-worker")
AUTHENTICATING_SERVICE = "repo-intelligence"
TENANT_READERS = ("workflow-worker", *READERS)
REGISTRY_LABEL = "com.agentic-platform.registry-sha256"
REGISTRY_FILE = "repositories.yaml"
_ENV_NAME = re.compile(r"^[A-Z_][A-Z0-9_]*$")
HEADER = (
    "# Generated by inv repos-compose from the folders of config/local/tenants/ and each "
    "tenant's repositories.yaml. Do not edit.\n"
)


def config_paths(tenants: Sequence[str], *, root: Path) -> list[Path]:
    """Return each tenant bundle directory that exists on the host."""
    config = env_config_dir(root=root)
    bundles = [config / "tenants" / tenant for tenant in tenants]
    return [bundle for bundle in bundles if bundle.is_dir()]


def registry_digest(config: Iterable[Path], *, root: Path) -> str:
    """Return the SHA-256 of every registry file the config mounts expose, keyed by its path."""
    files = sorted(
        candidate
        for path in config
        if (candidate := path if path.is_file() else path / REGISTRY_FILE).is_file()
    )
    digest = hashlib.sha256()
    for path in files:
        digest.update(path.relative_to(root).as_posix().encode() + b"\0")
        digest.update(path.read_bytes() + b"\0")
    return digest.hexdigest()


def token_environment(tenants: Sequence[str]) -> dict[str, str]:
    """Pass each tenant's REPO_INTELLIGENCE_TOKEN_<TENANT> through from the compose environment."""
    from services.repository_intelligence.tenant_tokens import token_env_name

    names = [token_env_name(tenant) for tenant in tenants]
    return {name: f"${{{name}:-}}" for name in names if _ENV_NAME.match(name)}


def render(
    registries: Iterable[RepositoryRegistry],
    *,
    base: Path,
    config: Sequence[Path] = (),
    tenants: Sequence[str] = (),
) -> dict[str, Any]:
    """Return the compose override naming the tenants and mounting each config path and each
    repository with a path."""
    config_mounts = [
        f"{path}:{CONTAINER_ROOT / path.relative_to(base).as_posix()}:ro" for path in config
    ]
    checkout_mounts = [
        f"{host}:{registry.root.rstrip('/')}/{name}:ro"
        for registry in registries
        for name in sorted(registry.repositories)
        if (host := registry.host_path(name, base)) is not None
    ]
    labels = {REGISTRY_LABEL: registry_digest(config, root=base)}
    tokens = token_environment(tenants)
    listed = {"TENANTS": ",".join(tenants)}
    services: dict[str, Any] = {}
    for reader in TENANT_READERS:
        service: dict[str, Any] = {"environment": dict(listed)}
        if reader == AUTHENTICATING_SERVICE:
            service["environment"].update(tokens)
        if reader in READERS:
            service["labels"] = dict(labels)
            service["volumes"] = config_mounts + checkout_mounts
        services[reader] = service
    return {"services": services}


def registry_config_dir(tenant: str, *, root: Path) -> Path:
    """Return the tenant's bundle directory, which holds its repositories.yaml."""
    from services.integration.credentials import ConfigError

    bundle = env_config_dir(root=root) / "tenants" / tenant
    if not (bundle / REGISTRY_FILE).is_file():
        raise ConfigError(
            f"tenant {tenant} names no repositories. Copy config/local/tenants/tenant.example/ to "
            f"config/local/tenants/{tenant}/ and edit its repositories.yaml"
        )
    return bundle


def tenant_registries(
    settings: Settings, tenants: Sequence[str], *, root: Path
) -> list[RepositoryRegistry]:
    """Return each tenant's registry, rooted at the tenant's repository directory."""
    from services.integration.credentials import load_env_config, require_current_config
    from services.integration.repositories import CONFIG_NAME, parse_repositories

    from scripts.tenant_render import worker_env

    registries = []
    for tenant in tenants:
        config_dir = registry_config_dir(tenant, root=root)
        require_current_config(CONFIG_NAME, directory=config_dir)
        raw = load_env_config(CONFIG_NAME, directory=config_dir)
        registries.append(parse_repositories(raw, root=worker_env(tenant)["REPOSITORY_ROOT"]))
    return registries


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args(argv)

    from services.integration.credentials import ConfigError

    from scripts.local_tenants import TenantLayoutError, local_tenant_names

    settings = get_settings()
    try:
        tenants = local_tenant_names(env_config_dir(root=REPO_ROOT))
        if not tenants:
            raise TenantLayoutError(
                "config/local/tenants/ holds no tenant. Copy config/local/tenants/tenant.example/ "
                "to config/local/tenants/<tenant>/ and config/local/tenants/tenant.example.env to "
                "config/local/tenants/<tenant>.env"
            )
        registries = tenant_registries(settings, tenants, root=REPO_ROOT)
    except (ConfigError, TenantLayoutError) as exc:
        print(f"[repos-compose] {exc}")
        return 1
    missing = sorted(
        {
            f"{name} at {path}"
            for registry in registries
            for name in registry.repositories
            if (path := registry.host_path(name, REPO_ROOT)) is not None and not path.is_dir()
        }
    )
    if missing:
        print(f"[repos-compose] repository checkouts not found: {', '.join(missing)}")
        return 1
    config = config_paths(tenants, root=REPO_ROOT)
    rendered = render(registries, base=REPO_ROOT, config=config, tenants=tenants)
    args.output.write_text(HEADER + yaml.safe_dump(rendered, sort_keys=False), encoding="utf-8")
    volumes = rendered["services"][READERS[0]]["volumes"]
    print(
        f"[repos-compose] wrote {args.output.name} with {len(volumes)} mount(s) on each of "
        f"{', '.join(READERS)}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
