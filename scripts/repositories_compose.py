"""Write the compose override that mounts the repository intelligence registry and checkouts.

The repositories each tenant works on come from config/<env>/tenants/<tenant>/repositories.yaml,
or from config/<env>/repositories.yaml for a tenant whose bundle holds none, so the committed
compose files name none of them. This renders compose.repositories.yaml for the repository
intelligence services, for each tenant TENANTS names, or else TENANT. It mounts read-only
config/<env>/repositories.yaml, each served tenant's bundle directory that exists, and every
repository that names a path at /tenants/<tenant>/repositories/<name>. Without a tenant it mounts
config/<env>/repositories.yaml and its repositories at REPOSITORY_ROOT/<name>. The in-cluster
workers receive their copies through inv repos-sync.

A single-file bind mount keeps the inode it was created with, so an editor that saves
repositories.yaml by replacing the file is not seen inside the container. Each service carries
the label REGISTRY_LABEL, a digest of the registry files it mounts, so docker compose up -d
recreates the services once inv repos-compose runs after an edit.
"""

from __future__ import annotations

import argparse
import hashlib
import re
from collections.abc import Iterable, Sequence
from pathlib import Path, PurePosixPath
from typing import TYPE_CHECKING, Any

import yaml

from scripts.config import Settings, get_settings

if TYPE_CHECKING:
    from services.integration.repositories import RepositoryRegistry

REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT = REPO_ROOT / "compose.repositories.yaml"
CONTAINER_ROOT = PurePosixPath("/app")
READERS = ("repo-intelligence", "repo-index-worker")
AUTHENTICATING_SERVICE = "repo-intelligence"
REGISTRY_LABEL = "com.agentic-platform.registry-sha256"
REGISTRY_FILE = "repositories.yaml"
_ENV_NAME = re.compile(r"^[A-Z_][A-Z0-9_]*$")
HEADER = (
    "# Generated by inv repos-compose from config/<env>/tenants/<tenant>/repositories.yaml, or "
    "config/<env>/repositories.yaml for a tenant without one. Do not edit.\n"
)


def config_paths(environment: str, tenants: Sequence[str], *, root: Path) -> list[Path]:
    """Return the environment registry and each tenant bundle directory that exist on the host."""
    config = root / "config" / environment
    registry = config / REGISTRY_FILE
    bundles = [config / "tenants" / tenant for tenant in tenants]
    return ([registry] if registry.is_file() else []) + [b for b in bundles if b.is_dir()]


def registry_digest(config: Iterable[Path], *, root: Path) -> str:
    """Return the SHA-256 of every registry file the config mounts expose, keyed by its path."""
    files = sorted(
        candidate
        for path in config
        if (candidate := path if path.is_file() else path / REGISTRY_FILE).is_file()
    )
    digest = hashlib.sha256()
    for path in files:
        digest.update(path.relative_to(root).as_posix().encode() + b"\0")
        digest.update(path.read_bytes() + b"\0")
    return digest.hexdigest()


def token_environment(tenants: Sequence[str]) -> dict[str, str]:
    """Pass each tenant's REPO_INTELLIGENCE_TOKEN_<TENANT> through from the compose environment."""
    from services.repository_intelligence.tenant_tokens import token_env_name

    names = [token_env_name(tenant) for tenant in tenants]
    return {name: f"${{{name}:-}}" for name in names if _ENV_NAME.match(name)}


def render(
    registries: Iterable[RepositoryRegistry],
    *,
    base: Path,
    config: Sequence[Path] = (),
    tenants: Sequence[str] = (),
) -> dict[str, Any]:
    """Return the compose override mounting the config paths and each repository with a path."""
    config_mounts = [
        f"{path}:{CONTAINER_ROOT / path.relative_to(base).as_posix()}:ro" for path in config
    ]
    checkout_mounts = [
        f"{host}:{registry.root.rstrip('/')}/{name}:ro"
        for registry in registries
        for name in sorted(registry.repositories)
        if (host := registry.host_path(name, base)) is not None
    ]
    labels = {REGISTRY_LABEL: registry_digest(config, root=base)}
    tokens = token_environment(tenants)
    services: dict[str, Any] = {}
    for reader in READERS:
        service: dict[str, Any] = {"labels": dict(labels)}
        if reader == AUTHENTICATING_SERVICE and tokens:
            service["environment"] = dict(tokens)
        service["volumes"] = config_mounts + checkout_mounts
        services[reader] = service
    return {"services": services}


def tenant_registries(
    settings: Settings, tenants: Sequence[str], *, root: Path
) -> list[RepositoryRegistry]:
    """Return each tenant's registry, rooted at the tenant's repository directory."""
    from services.integration.credentials import load_env_config, require_current_config
    from services.integration.repositories import CONFIG_NAME, parse_repositories

    from scripts.tenant_render import worker_env

    registries = []
    for tenant in tenants:
        bundle = f"{settings.environment}/tenants/{tenant}"
        has_own = (root / "config" / bundle / f"{CONFIG_NAME}.yaml").is_file()
        config_dir = bundle if has_own else settings.environment
        require_current_config(CONFIG_NAME, environment=config_dir, root=root)
        raw = load_env_config(CONFIG_NAME, environment=config_dir, root=root)
        registries.append(parse_repositories(raw, root=worker_env(tenant)["REPOSITORY_ROOT"]))
    return registries


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args(argv)

    from services.integration.repositories import load_repository_registry
    from services.orchestration.task_queues import tenant_names

    settings = get_settings()
    tenants = tenant_names(settings) or ([settings.tenant] if settings.tenant else [])
    registries = (
        tenant_registries(settings, tenants, root=REPO_ROOT)
        if tenants
        else [load_repository_registry(settings, root=REPO_ROOT)]
    )
    missing = sorted(
        {
            f"{name} at {path}"
            for registry in registries
            for name in registry.repositories
            if (path := registry.host_path(name, REPO_ROOT)) is not None and not path.is_dir()
        }
    )
    if missing:
        print(f"[repos-compose] repository checkouts not found: {', '.join(missing)}")
        return 1
    config = config_paths(settings.environment, tenants, root=REPO_ROOT)
    rendered = render(registries, base=REPO_ROOT, config=config, tenants=tenants)
    args.output.write_text(HEADER + yaml.safe_dump(rendered, sort_keys=False), encoding="utf-8")
    volumes = rendered["services"][READERS[0]]["volumes"]
    print(
        f"[repos-compose] wrote {args.output.name} with {len(volumes)} mount(s) on each of "
        f"{', '.join(READERS)}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
