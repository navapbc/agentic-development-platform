"""Write the compose override that mounts each configured repository's host checkout.

The repositories an environment works on come from config/<env>/repositories.yaml, so the
committed compose files name none of them. This renders compose.repositories.yaml, which mounts
every repository that names a path at REPOSITORY_ROOT/<name> in the services that read
checkouts. The activity worker mounts a local-backend repository read-write, because it
pushes branches into it, and every other mount is read-only.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

import yaml

from scripts.config import get_settings

REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT = REPO_ROOT / "compose.repositories.yaml"
WRITER = "activity-worker"
READERS = ("repo-intelligence", "repo-index-worker")
HEADER = "# Generated by inv repos-compose from config/<env>/repositories.yaml. Do not edit.\n"


def render(registry: Any, *, base: Path, container_root: str) -> dict[str, Any]:
    """Return the compose override mounting each repository that names a path."""
    from services.integration.repositories import LOCAL

    writer: list[str] = []
    readers: list[str] = []
    for name in sorted(registry.repositories):
        host = registry.host_path(name, base)
        if host is None:
            continue
        target = f"{container_root.rstrip('/')}/{name}"
        mode = "" if registry.repositories[name].backend == LOCAL else ":ro"
        writer.append(f"{host}:{target}{mode}")
        readers.append(f"{host}:{target}:ro")
    services: dict[str, Any] = {WRITER: {"volumes": writer}} if writer else {}
    services.update({reader: {"volumes": readers} for reader in READERS if readers})
    return {"services": services}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args(argv)

    from services.integration.repositories import load_repository_registry

    settings = get_settings()
    registry = load_repository_registry(settings)
    missing = [
        f"{name} at {path}"
        for name in sorted(registry.repositories)
        if (path := registry.host_path(name, REPO_ROOT)) is not None and not path.is_dir()
    ]
    if missing:
        print(f"[repos-compose] repository checkouts not found: {', '.join(missing)}")
        return 1
    rendered = render(registry, base=REPO_ROOT, container_root=settings.repository_root)
    args.output.write_text(HEADER + yaml.safe_dump(rendered, sort_keys=False), encoding="utf-8")
    mounted = sum(len(service["volumes"]) for service in rendered["services"].values())
    print(f"[repos-compose] wrote {args.output.name} with {mounted} mount(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
